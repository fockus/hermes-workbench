"""The big task class (AGR-103): five tasks where direct mode needs dozens of sequential requests, so
code mode has room to win. Not part of ``TASK_SET``: the twelve-task protocol stays as it is. Fixtures
are generated by ``setup`` and fixed, so a check has one right outcome. The eval agent has only the
``file`` toolset (read_file, write_file, patch, search_files)."""

from __future__ import annotations

import re
from pathlib import Path

from .tasks import EvalTask, _files, _number, _read

NUMBER_ONLY = " Answer with the number only."
LEDGER_LINES = 6000  # twelve pages of 500 lines
FLAGGED = {i for i in range(200) if i % 7 in (1, 4)}
HIGH = {"n%02d.note" % i for i in range(40) if i % 3 == 0}
EDITED = 36
LOG_LINES = 24_000
_SERVICES = ("auth", "billing", "search", "mail", "media")
_LEVELS = ("INFO", "INFO", "WARN", "ERROR", "INFO")


def _flagged_files(wd: Path) -> None:
    _files(wd / "files", {"f%03d.txt" % i: "record %d\nstatus: %s\n" % (i, "flagged" if i in FLAGGED else "clean")
                          for i in range(200)})


def _ledger(wd: Path) -> None:
    (wd / "ledger.txt").write_text("".join("tx%05d amount=%d\n" % (i, (i * 31) % 97 + 1) for i in range(LEDGER_LINES)))


def _inbox(wd: Path) -> None:
    for i in range(40):
        folder = wd / "inbox" / "abcd"[i % 4]
        priority = "high" if "n%02d.note" % i in HIGH else "low"
        _files(folder, {"n%02d.note" % i: "priority: %s\nbody of note %d\n" % (priority, i)})
    _files(wd / "inbox" / "old", {"x%d.txt" % i: "priority: high\nnot a note\n" for i in range(10)})


def _urgent_ok(wd: Path) -> bool:
    text = _read(wd / "urgent.txt")
    return text is not None and [ln.strip() for ln in text.splitlines() if ln.strip()] == sorted(HIGH)


def _configs(wd: Path) -> None:
    _files(wd / "conf", {"svc%02d.cfg" % i: "[svc]\nname=svc%d\ntimeout=30\nretries=%d\n" % (i, i % 5)
                         for i in range(EDITED)})


def _timeouts_ok(wd: Path) -> bool:
    expected = {"svc%02d.cfg" % i for i in range(EDITED)}
    if {p.relative_to(wd / "conf").as_posix() for p in (wd / "conf").rglob("*")} != expected:
        return False  # "change nothing else": no extra file, backup or folder
    return all(_read(wd / "conf" / ("svc%02d.cfg" % i)) == "[svc]\nname=svc%d\ntimeout=60\nretries=%d\n" % (i, i % 5)
               for i in range(EDITED))


def _log_line(i: int) -> str:
    return "t=%06d level=%s svc=%s ms=%d" % (i, _LEVELS[i % 5], _SERVICES[(i * 3 + i // 7) % 5], (i * 13) % 250 + 1)


def _server_log(wd: Path) -> None:
    (wd / "server.log").write_text("".join(_log_line(i) + "\n" for i in range(LOG_LINES)))


def _billing_error_ms() -> int:
    return sum(int(re.search(r"ms=(\d+)", ln).group(1)) for ln in map(_log_line, range(LOG_LINES))
               if "level=ERROR svc=billing " in ln)


BIG_TASKS: tuple[EvalTask, ...] = (
    EvalTask(
        "big-count-files", "big",
        "{wd}/files has 200 text files. How many of them contain the word flagged?" + NUMBER_ONLY,
        _flagged_files,
        lambda a, wd: _number(a, wd, len(FLAGGED)),
    ),
    EvalTask(
        "big-pages-sum", "big",
        "{wd}/ledger.txt has 6000 lines like `tx00001 amount=17`. Read it 500 lines per page until the end "
        "and sum the amount of every line." + NUMBER_ONLY,
        _ledger,
        lambda a, wd: _number(a, wd, sum((i * 31) % 97 + 1 for i in range(LEDGER_LINES))),
    ),
    EvalTask(
        "big-find-filter-write", "big",
        "Find every file named *.note under {wd}/inbox, sub folders included (there are 40). Read each one. "
        "Write {wd}/urgent.txt with the names of the notes whose first line is `priority: high`, one per "
        "line, sorted. Ignore files that are not .note files.",
        _inbox,
        lambda a, wd: _urgent_ok(wd),
    ),
    EvalTask(
        "big-mass-edit", "big",
        "In every .cfg file in {wd}/conf (36 files) change timeout=30 to timeout=60 and change nothing else.",
        _configs,
        lambda a, wd: _timeouts_ok(wd),
    ),
    EvalTask(
        "big-log-summary", "big",
        "{wd}/server.log has one request per line: `t=<n> level=<LEVEL> svc=<name> ms=<n>`. What is the total "
        "of ms over the lines with level ERROR and svc billing?" + NUMBER_ONLY,
        _server_log,
        lambda a, wd: _number(a, wd, _billing_error_ms()),
    ),
)
